"""Tradable derivative product universe driven by existing market mechanics."""

from __future__ import annotations

import math
from datetime import datetime, timedelta
from types import ModuleType
from typing import Any

from kojakstreet.core.countries import COUNTRIES, RESERVE_CURRENCY
from kojakstreet.core.ohlc import append_ohlc_from_move

FUTURE_TENORS = (1, 3, 6)
OPTION_TENORS = (1, 3)
OPTION_MONEYNESS = (0.95, 1.0, 1.05)
YIELD_TENORS = (2, 5, 10, 30)
CDS_NOTIONAL = 10_000_000.0
CDS_RECOVERY_RATE = 0.40
CDS_CONTRACT_SCALE = 10_000.0
DERIVATIVE_MARKET_CAP = 100_000_000.0
EXPIRING_DERIVATIVE_CONTRACT_TYPES = {
    "Commodity Future",
    "Commodity Spread Future",
    "FX Forward",
    "Freight Future",
    "Inflation Swap",
    "Input-Cost Spread",
    "Yield Future",
}
CDS_CONTRACT_TYPES = {"Credit Default Swap", "Corporate Credit Default Swap"}
SPOT_SETTLED_DERIVATIVE_TYPES = {"Option", *CDS_CONTRACT_TYPES}


def derivative_allows_spot_trade(asset: dict[str, Any]) -> bool:
    return str(asset.get("instrument_type", "")) in SPOT_SETTLED_DERIVATIVE_TYPES


def derivative_allows_future_trade(asset: dict[str, Any]) -> bool:
    return str(asset.get("instrument_type", "")) in EXPIRING_DERIVATIVE_CONTRACT_TYPES


def derivative_use_case(asset: dict[str, Any]) -> str:
    instrument_type = str(asset.get("instrument_type", ""))
    if instrument_type == "Commodity Future":
        return "Locks or speculates on a future raw-material or processed-product price."
    if instrument_type == "Commodity Spread Future":
        return "Trades relative scarcity between two linked commodity or logistics markets."
    if instrument_type == "Freight Future":
        return "Hedges transport and shipping-rate pressure across global trade routes."
    if instrument_type == "Input-Cost Spread":
        return "Tracks the margin between a finished product and its weighted input basket."
    if instrument_type == "FX Forward":
        return "Hedges exchange-rate and interest-rate-differential exposure."
    if instrument_type == "Inflation Swap":
        return "Hedges unexpected inflation against a fixed inflation strike."
    if instrument_type == "Yield Future":
        return "Expresses or hedges interest-rate and yield-curve risk."
    if instrument_type == "Option":
        return "Buys convex upside or downside exposure with expiry settlement."
    if instrument_type in CDS_CONTRACT_TYPES:
        return "Buys credit protection against sovereign or corporate default."
    return "Derivative exposure driven by its referenced market."


def derivative_pricing_note(asset: dict[str, Any]) -> str:
    instrument_type = str(asset.get("instrument_type", ""))
    if instrument_type in CDS_CONTRACT_TYPES:
        scale = float(asset.get("contract_scale", CDS_CONTRACT_SCALE) or CDS_CONTRACT_SCALE)
        notional = float(asset.get("notional", CDS_NOTIONAL) or CDS_NOTIONAL)
        return (
            "Displayed price is a scaled protection-value indicator, not an equity-style quote "
            f"(notional {notional:,.0f}, scale {scale:,.0f})."
        )
    if instrument_type == "Option":
        return "Displayed price combines intrinsic value and simplified time value."
    if instrument_type in EXPIRING_DERIVATIVE_CONTRACT_TYPES:
        return "Displayed price is a simulation mark for futures-style long/short exposure."
    return "Displayed price is generated by the simulation model."


def ensure_financial_product_universe(daten: ModuleType, *, reset: bool = False) -> None:
    if reset or not hasattr(daten, "derivatives"):
        daten.derivatives = {}
    derivatives: dict[str, dict[str, Any]] = daten.derivatives
    if derivatives and getattr(daten, "derivative_universe_complete", False):
        return
    derivatives.clear()
    _add_commodity_futures(daten, derivatives)
    _add_cds_contracts(daten, derivatives)
    _add_corporate_cds_contracts(daten, derivatives)
    _add_options(daten, derivatives)
    _add_yield_futures(daten, derivatives)
    _add_fx_forwards(daten, derivatives)
    _add_inflation_swaps(daten, derivatives)
    _add_commodity_spread_futures(daten, derivatives)
    _add_input_cost_spreads(daten, derivatives)
    _add_freight_futures(daten, derivatives)
    daten.derivative_universe_complete = True


def update_financial_products(daten: ModuleType, zeit_str: str) -> None:
    ensure_financial_product_universe(daten)
    for ticker, product, instrument_type in _financial_product_runtimes(daten):
        old_price = float(product.get("kurs", 100.0))
        price = _price_product(daten, ticker, product, instrument_type)
        product["kurs"] = max(0.01, price)
        product["aenderung"] = ((product["kurs"] - old_price) / old_price * 100.0) if old_price > 0 else 0.0
        product["market_cap"] = float(product.get("open_interest", DERIVATIVE_MARKET_CAP))
        append_ohlc_from_move(product, old_price, product["kurs"], zeit_str, limit=1040)


def roll_expired_financial_products(daten: ModuleType) -> None:
    today = getattr(daten, "datum", None)
    if not isinstance(today, datetime):
        return
    for _ticker, product, instrument_type in _financial_product_runtimes(daten):
        expires_at = _parse_date(product.get("expires_at"))
        if expires_at is None or today < expires_at:
            continue
        if instrument_type == "Option":
            _reset_option_contract(daten, product)
        elif instrument_type == "Credit Default Swap":
            _reset_cds_contract(daten, product)


def _financial_product_runtimes(daten: ModuleType) -> list[tuple[str, dict[str, Any], str]]:
    derivatives = getattr(daten, "derivatives", {})
    signature = tuple((ticker, id(product), str(product.get("instrument_type", ""))) for ticker, product in derivatives.items())
    cache = getattr(daten, "_financial_product_runtime_cache", None)
    if isinstance(cache, dict) and cache.get("signature") == signature:
        return cache["products"]
    products = [
        (str(ticker), product, str(product.get("instrument_type", "")))
        for ticker, product in derivatives.items()
    ]
    daten._financial_product_runtime_cache = {"signature": signature, "products": products}
    return products


def _add_commodity_futures(daten: ModuleType, derivatives: dict[str, dict[str, Any]]) -> None:
    underlyings = list(getattr(daten, "rohstoffe", {}).items())[:24]
    products = list(getattr(daten, "processed_products", {}).items())[:18]
    for code, asset in [*underlyings, *products]:
        for tenor in FUTURE_TENORS:
            ticker = f"F{code}{tenor}M"[:8]
            derivatives[ticker] = _base_product(
                name=f"{asset.get('name', code)} {tenor}M Future",
                instrument_type="Commodity Future",
                underlying=str(code),
                tenor_months=tenor,
                region=RESERVE_CURRENCY,
                sector=str(asset.get("kategorie", asset.get("category", "Futures"))),
            )


def _add_cds_contracts(daten: ModuleType, derivatives: dict[str, dict[str, Any]]) -> None:
    for country in COUNTRIES:
        ticker = f"CDS{country.code}"
        product = _base_product(
            name=f"{country.name} 5Y Sovereign CDS",
            instrument_type="Credit Default Swap",
            underlying=country.name,
            tenor_months=60,
            notional=CDS_NOTIONAL,
            contract_scale=CDS_CONTRACT_SCALE,
            contract_size=CDS_NOTIONAL / CDS_CONTRACT_SCALE,
            recovery_rate=CDS_RECOVERY_RATE,
            region=country.name,
            sector="Sovereign Credit",
        )
        _reset_cds_contract(daten, product)
        derivatives[ticker] = product


def _add_corporate_cds_contracts(daten: ModuleType, derivatives: dict[str, dict[str, Any]]) -> None:
    for ticker, asset in list(getattr(daten, "aktien", {}).items())[:120]:
        symbol = f"CDX{ticker}"[:8]
        product = _base_product(
            name=f"{asset.get('name', ticker)} 5Y Corporate CDS",
            instrument_type="Corporate Credit Default Swap",
            underlying=str(ticker),
            underlying_type="Corporate",
            tenor_months=60,
            notional=CDS_NOTIONAL,
            contract_scale=CDS_CONTRACT_SCALE,
            contract_size=CDS_NOTIONAL / CDS_CONTRACT_SCALE,
            recovery_rate=0.35,
            region=str(asset.get("land", RESERVE_CURRENCY)),
            sector="Corporate Credit",
        )
        _reset_cds_contract(daten, product)
        derivatives[symbol] = product


def _add_options(daten: ModuleType, derivatives: dict[str, dict[str, Any]]) -> None:
    underlyings = []
    underlyings.extend((ticker, asset, "Index") for ticker, asset in list(getattr(daten, "indizes", {}).items())[:10])
    underlyings.extend((ticker, asset, "Commodity") for ticker, asset in list(getattr(daten, "rohstoffe", {}).items())[:8])
    for ticker, asset, asset_type in underlyings:
        for tenor in OPTION_TENORS:
            for moneyness in OPTION_MONEYNESS:
                for option_type in ("CALL", "PUT"):
                    strike_pct = round(moneyness * 100)
                    symbol = f"O{ticker[:3]}{option_type[0]}{strike_pct}{tenor}"
                    product = _base_product(
                        name=f"{asset.get('name', ticker)} {option_type.title()} {strike_pct}% {tenor}M",
                        instrument_type="Option",
                        underlying=str(ticker),
                        underlying_type=asset_type,
                        tenor_months=tenor,
                        option_type=option_type,
                        strike_moneyness=moneyness,
                        region=str(asset.get("land", asset.get("ziel", RESERVE_CURRENCY))),
                        sector=f"{asset_type} Options",
                    )
                    _reset_option_contract(daten, product)
                    derivatives[symbol] = product


