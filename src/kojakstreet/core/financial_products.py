def _region_code(region: str) -> str:
    if region == RESERVE_CURRENCY:
        return "GD"
    for country in COUNTRIES:
        if country.name == region:
            return country.code
    return "".join(char for char in str(region).upper() if char.isalpha())[:3] or "REG"


def _currency_label(region: str) -> str:
    return "GD" if region == RESERVE_CURRENCY else _region_code(region)


def _implied_volatility(daten: ModuleType, asset: dict[str, Any], asset_type: str) -> float:
    vix = float(getattr(daten, "global_macro", {}).get("vix", 18.0)) / 100.0
    own_move = abs(float(asset.get("aenderung", 0.0))) / 100.0 * 5.0
    base = 0.18 if asset_type == "Index" else 0.24
    return max(0.08, min(0.95, base + vix * 0.45 + own_move))
